export function tr(clau, lang = 'ca', vars) {
  const s = UI[clau]?.[lang] ?? UI[clau]?.ca ?? clau
  if (!vars) return s
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`))
}

// Idioma per defecte segons el navegador: català si el sistema hi és, si no anglès.
export function idiomaPerDefecte() {
  const l = (navigator.languages || [navigator.language || 'en']).join(',').toLowerCase()
  return /\bca\b|ca-/.test(l) ? 'ca' : 'en'
}
